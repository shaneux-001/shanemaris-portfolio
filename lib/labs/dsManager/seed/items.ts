/*
 * Seed inventory for the fictional system. Deliberately messy in the ways
 * real systems are — drift between platforms, unowned components, stale
 * docs, a product component that duplicates a system one — so the
 * dashboard's health metrics have something real to find.
 */

const STATUSES: PlatformStatus[] = ['shipped', 'in-progress', 'planned', 'not-planned', 'n/a'];

/** `'3.2.0'` → shipped at that version; a status keyword → that status; an object → as-is. */
function impl(v: string | PlatformImpl): PlatformImpl {
  if (typeof v !== 'string') return v;
  if ((STATUSES as string[]).includes(v)) return { status: v as PlatformStatus };
  return { status: 'shipped', version: v };
}

function plat(web: string | PlatformImpl, ios: string | PlatformImpl, android: string | PlatformImpl, figma: string | PlatformImpl) {
  return { web: impl(web), ios: impl(ios), android: impl(android), figma: impl(figma) };
}

/** Fully ready except for whatever is listed. */
function ready(...missing: (keyof Readiness)[]): Readiness {
  const r: Readiness = { design: true, code: true, docs: true, a11y: true, tokens: true, tests: true };
  missing.forEach((k) => (r[k] = false));
  return r;
}

function docs(d: Partial<UsageDocs> & { summary: string }): UsageDocs {
  return { whenToUse: [], whenNotToUse: [], dos: [], donts: [], a11y: [], ...d };
}

let seq = 0;
interface Input {
  name: string;
  slug?: string;
  kind?: ItemKind;
  category: Category;
  description: string;
  aliases?: string[];
  lifecycle: Lifecycle;
  version: string;
  ownerId?: string;
  productTeamId?: string;
  platforms: SystemItem['platforms'];
  readiness: Readiness;
  a11yLevel: A11yLevel;
  adoption: [number, number];
  dependencies?: string[];
  tokens?: string[];
  variants?: string[];
  props?: PropDef[];
  docs: UsageDocs;
  related?: string[];
  replacedBy?: string;
  promotionCandidate?: boolean;
  createdAt: string;
  updatedAt: string;
  docsUpdatedAt?: string;
}

function item(i: Input): SystemItem {
  seq += 1;
  const slug = i.slug ?? i.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
  return {
    id: `MER-${String(seq).padStart(3, '0')}`,
    slug,
    name: i.name,
    kind: i.kind ?? 'component',
    category: i.category,
    description: i.description,
    aliases: i.aliases ?? [],
    lifecycle: i.lifecycle,
    version: i.version,
    ownerId: i.ownerId,
    productTeamId: i.productTeamId,
    platforms: i.platforms,
    readiness: i.readiness,
    a11yLevel: i.a11yLevel,
    adoption: { products: i.adoption[0], instances: i.adoption[1] },
    dependencies: i.dependencies ?? [],
    tokens: i.tokens ?? [],
    variants: i.variants ?? [],
    props: i.props ?? [],
    docs: i.docs,
    related: i.related ?? [],
    replacedBy: i.replacedBy,
    promotionCandidate: i.promotionCandidate,
    createdAt: i.createdAt,
    updatedAt: i.updatedAt,
    docsUpdatedAt: i.docsUpdatedAt ?? i.updatedAt,
  };
}

